#pragma once

#include <stddef.h>
#include <stdint.h>

/**
 * @file rsa.h
 * @brief Интерфейс асимметричного шифра RSA с длиной модуля 32768 бит.
 *
 * Реализация использует многопростой RSA (RFC 8017 §3): модуль n
 * собирается из CSLR_RSA_NUM_PRIMES простых чисел равной длины.
 * Число простых задаётся константой CSLR_RSA_NUM_PRIMES (значение
 * по умолчанию — 4) и должно делить CSLR_RSA_KEY_BITS без остатка.
 * Значение можно переопределить при компиляции:
 *     gcc -DCSLR_RSA_NUM_PRIMES=8 ...
 *
 * Режим — raw RSA (RSAEP/RSADP по RFC 8017 §5.1), без паддинга.
 * Сообщения произвольной длины разбиваются на блоки по
 * CSLR_RSA_KEY_BYTES байт; неполный последний блок дополняется
 * нулями слева (big-endian) до полного размера блока.
 *
 * ВНИМАНИЕ: raw RSA без паддинга не является криптостойкой схемой
 * шифрования. Реализация предназначена для учебных целей.
 */

/** Длина модуля в битах. */
#define CSLR_RSA_KEY_BITS  32768
/** Длина модуля в байтах (4096). */
#define CSLR_RSA_KEY_BYTES (CSLR_RSA_KEY_BITS / 8)

/**
 * @brief Число простых множителей модуля n (многопростой RSA).
 *
 * Должно делить CSLR_RSA_KEY_BITS без остатка и лежать в разумных
 * пределах (2..10). При 2 — классический RSA с двумя простыми;
 * при >2 — многопростой RSA (RFC 8017 §3), который ускоряет
 * генерацию ключа и расшифрование за счёт более коротких простых.
 */
#ifndef CSLR_RSA_NUM_PRIMES
#define CSLR_RSA_NUM_PRIMES 4
#endif

/**
 * @brief Открытый ключ RSA-32768 (модуль n и открытая экспонента e в big-endian).
 *
 * Поля n и e — беззнаковые целые в big-endian, дополненные нулями
 * слева до CSLR_RSA_KEY_BYTES байт. Старшие нули игнорируются при
 * интерпретации числа.
 */
struct cslr_rsa_pub_key {
    uint8_t n[CSLR_RSA_KEY_BYTES];
    uint8_t e[CSLR_RSA_KEY_BYTES];
};

/**
 * @brief Закрытый ключ RSA-32768 (модуль n и закрытая экспонента d в big-endian).
 *
 * Поля n и d — беззнаковые целые в big-endian, дополненные нулями
 * слева до CSLR_RSA_KEY_BYTES байт.
 */
struct cslr_rsa_priv_key {
    uint8_t n[CSLR_RSA_KEY_BYTES];
    uint8_t d[CSLR_RSA_KEY_BYTES];
};

/**
 * @brief Генерирует пару ключей RSA длиной 32768 бит.
 *
 * Модуль n собирается из CSLR_RSA_NUM_PRIMES простых чисел длины
 * CSLR_RSA_KEY_BITS / CSLR_RSA_NUM_PRIMES бит каждое. Открытая
 * экспонента e фиксирована и равна 65537; при генерации простых
 * кандидаты p с p ≡ 1 (mod e) отсеиваются, чтобы гарантировать
 * НОД(e, φ(n)) = 1.
 *
 * ВНИМАНИЕ: генерация ключа RSA-32768 — длительная операция
 * (от десятков минут до часов в зависимости от числа простых и
 * производительности машины). Не предназначена для вызова в
 * интерактивном режиме или в юнит-тестах.
 *
 * @param[out] pub  Указатель на структуру для записи открытого ключа.
 * @param[out] priv Указатель на �труктуру для записи закрытого ключа.
 * @return 0 при успешной генерации, -1 при ошибке или передаче NULL.
 */
int cslr_rsa_keygen(struct cslr_rsa_pub_key *pub,
                    struct cslr_rsa_priv_key *priv);

/**
 * @brief Шифрует массив байт открытым ключом RSA (raw RSA, без паддинга).
 *
 * Входные данные разбиваются на блоки по CSLR_RSA_KEY_BYTES (4096)
 * байт. Неполный последний блок дополняется нулями слева (big-endian)
 * до полного размера блока. Каждый блок m должен удовлетворять
 * m < n, иначе возвращается -1.
 *
 * При in_len == 0 функция возвращает 0 и устанавливает *out_len = 0
 * (пустой вход — пустой выход, без фиктивного блока).
 *
 * @param[in]  pub     Указатель на открытый ключ RSA.
 * @param[in]  in      Указатель на входные данные (может быть NULL при in_len == 0).
 * @param[in]  in_len  Длина входных данных в байтах.
 * @param[out] out     Выходной буфер; должен вмещать
 *                     ((in_len + CSLR_RSA_KEY_BYTES - 1) / CSLR_RSA_KEY_BYTES)
 *                     * CSLR_RSA_KEY_BYTES байт (0 при in_len == 0).
 * @param[out] out_len Указатель, куда будет записана итоговая длина
 *                     шифртекста в байтах (кратна CSLR_RSA_KEY_BYTES).
 * @return 0 при успешном шифровании, -1 при ошибке или некорректных аргументах.
 */
int cslr_rsa_encrypt(const struct cslr_rsa_pub_key *pub,
                     const uint8_t *in, size_t in_len,
                     uint8_t *out, size_t *out_len);

/**
 * @brief Расшифровывает массив байт закрытым ключом RSA (raw RSA).
 *
 * Длина in_len должна быть кратна CSLR_RSA_KEY_BYTES и больше нуля,
 * иначе возвращается -1. Каждый блок c должен удовлетворять c < n,
 * иначе возвращается -1.
 *
 * @param[in]  priv    Указатель на закрытый ключ RSA.
 * @param[in]  in      Указатель на шифртекст (длина кратна 4096 и > 0).
 * @param[in]  in_len  Длина шифртекста в байтах.
 * @param[out] out     Выходной буфер размером не менее in_len байт.
 * @param[out] out_len Указатель, куда будет записана длина результата
 *                     (равна in_len).
 * @return 0 при успешном расшифровании, -1 при ошибке или некорректных аргументах.
 */
int cslr_rsa_decrypt(const struct cslr_rsa_priv_key *priv,
                     const uint8_t *in, size_t in_len,
                     uint8_t *out, size_t *out_len);
